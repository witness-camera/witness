package com.witnessrecord.app.service

import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import android.text.Layout.Alignment
import android.text.StaticLayout
import android.text.TextPaint
import com.witnessrecord.app.WitnessApplication
import com.witnessrecord.app.model.SessionManifest
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import java.util.TimeZone

/**
 * Renders an archived session into a PDF an attorney or an editor can
 * actually work from.
 *
 * The raw artefacts are already complete - a manifest of hashes and an RFC
 * 3161 proof - but they are a JSON file and a binary blob, unreadable to the
 * people who decide what a recording is worth. This turns the same facts
 * into a document: what was filmed, when and where, which files exist, what
 * each one hashes to, and precisely how a third party can check all of it
 * without trusting this app or its author.
 *
 * Nothing here is generated or inferred. Every figure is copied from the
 * manifest that was hashed and counter-signed; the report adds presentation,
 * never content.
 */
object EvidenceReport {

    private const val PAGE_WIDTH = 595 // A4 at 72 dpi
    private const val PAGE_HEIGHT = 842
    private const val MARGIN = 48f
    private val CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2

    /** Writes the report to a cache file and returns it. */
    fun pdf(manifest: SessionManifest, hasTimestamp: Boolean): File {
        val document = PdfDocument()
        val layout = Layout(document)
        layout.beginPage()

        layout.title("Recording record")
        layout.caption("Generated by Witness on ${absolute(System.currentTimeMillis())}")
        layout.gap(10f)

        layout.heading("Session")
        layout.field("Identifier", manifest.sessionID)
        layout.field("Recording began", absolute(manifest.recordingStartedUTC))
        layout.field("Recording ended", absolute(manifest.recordingEndedUTC))
        layout.field("Duration", duration(manifest.recordingStartedUTC, manifest.recordingEndedUTC))
        layout.field("Device time zone", manifest.deviceTimeZone)
        layout.field("Segments recorded", "${manifest.chunkCount}")
        layout.gap(6f)

        layout.heading("Capture device")
        layout.field("Device", manifest.deviceModel)
        layout.field("Operating system", manifest.systemVersion)
        layout.field("Application", "Witness ${manifest.appVersion}")
        layout.gap(6f)

        firstCoordinate(manifest)?.let { (lat, lon) ->
            layout.heading("Location")
            layout.field("First fix", String.format(Locale.US, "%.5f, %.5f", lat, lon))
            layout.body(
                "Each segment below carries its own coordinates as recorded at the time it was captured. " +
                    "Positions come from the device's location services and are only as precise as those services allowed."
            )
            layout.gap(6f)
        }

        layout.heading("Authenticity")
        if (hasTimestamp) {
            layout.body(
                "The accompanying manifest.json was counter-signed by an independent RFC 3161 time-stamp " +
                    "authority, which certifies with its own key and clock that the file existed in exactly " +
                    "this form before the time recorded in timestamp.tsr. Because every segment's SHA-256 " +
                    "appears in that manifest, the certification extends to the footage itself."
            )
            manifest.timestampAuthority?.let { layout.field("Authority", it) }
            layout.gap(4f)
            layout.body("To verify independently, with no involvement from Witness or its author:")
            layout.mono("openssl ts -verify -data manifest.json \\\n  -in timestamp.tsr -CAfile <authority CA certificate>")
            layout.body("Any modification to the manifest, or to any file whose hash it lists, causes this check to fail.")
            layout.body("Or drop the videos, manifest.json and timestamp.tsr into witnesscamera.com/verify, which runs the same checks inside the browser without uploading anything.")
        } else {
            layout.body(
                "No time-stamp proof accompanies this session: the authority could not be reached when " +
                    "the recording ended. The hashes below are still a complete record of the files as " +
                    "captured, but they are attested by this device alone rather than counter-signed by an independent party."
            )
        }
        layout.gap(6f)

        manifest.markers?.takeIf { it.isNotEmpty() }?.let { marks ->
            layout.heading("Moments marked")
            layout.body(
                "Marked by the person recording, during the recording, with a tap or a volume-button press. " +
                    "They are part of the manifest the time-stamp proof covers."
            )
            marks.forEachIndexed { index, mark ->
                val offset = ((mark - manifest.recordingStartedUTC) / 1000).toInt().coerceAtLeast(0)
                layout.field(
                    "Mark ${index + 1}",
                    "${absolute(mark)}  (${offset / 60}:${"%02d".format(offset % 60)} into the recording)",
                )
            }
            layout.gap(6f)
        }

        layout.heading("Segments and hashes")
        layout.body(
            "Each entry is one file as uploaded. A SHA-256 hash identifies a file's contents exactly: " +
                "recomputing it over a copy and comparing establishes whether that copy is unaltered."
        )
        layout.gap(4f)
        layout.segmentTable(manifest.chunks)

        val merged = manifest.mergedVideos
        if (!merged.isNullOrEmpty()) {
            layout.gap(6f)
            layout.heading("Consolidated videos")
            layout.body(
                "Once every segment was safely uploaded, the segments of each camera were joined into a " +
                    "single file. These are the same footage, not a re-recording."
            )
            layout.gap(4f)
            layout.mergedTable(merged)
        }

        layout.gap(10f)
        layout.caption(
            "This document reproduces the contents of manifest.json. Where the two differ, the manifest " +
                "- being the file the time-stamp proof covers - governs."
        )

        layout.finishPage()

        val output = File(
            WitnessApplication.appContext.cacheDir,
            "Witness-${manifest.sessionID.take(8)}.pdf"
        )
        output.delete()
        FileOutputStream(output).use { document.writeTo(it) }
        document.close()
        return output
    }

    // MARK: - Helpers

    private fun absolute(epochMillis: Long): String {
        val formatter = SimpleDateFormat("yyyy-MM-dd HH:mm:ss 'UTC'", Locale.US)
        formatter.timeZone = TimeZone.getTimeZone("UTC")
        return formatter.format(Date(epochMillis))
    }

    private fun duration(startMillis: Long, endMillis: Long): String {
        val seconds = ((endMillis - startMillis) / 1000).coerceAtLeast(0)
        val minutes = seconds / 60
        val remainder = seconds % 60
        return if (minutes > 0) "$minutes min $remainder s" else "$remainder s"
    }

    private fun firstCoordinate(manifest: SessionManifest): Pair<Double, Double>? =
        manifest.chunks.sortedBy { it.index }
            .firstNotNullOfOrNull { chunk ->
                val lat = chunk.latitude
                val lon = chunk.longitude
                if (lat != null && lon != null) lat to lon else null
            }
}

/**
 * Minimal flowing-text layout over [PdfDocument]: tracks a cursor, breaks
 * pages when the next block wouldn't fit, and draws nothing that would
 * silently overflow the page.
 */
private class Layout(private val document: PdfDocument) {
    private var page: PdfDocument.Page? = null
    private var y = 0f
    private val left = 48f
    private val contentWidth = (595 - 96).toFloat()
    private val bottom = (842 - 48).toFloat()

    fun beginPage() {
        page?.let { document.finishPage(it) }
        val info = PdfDocument.PageInfo.Builder(595, 842, document.pages.size + 1).create()
        page = document.startPage(info)
        y = 48f
    }

    fun finishPage() {
        page?.let { document.finishPage(it) }
        page = null
    }

    private fun ensure(height: Float) {
        if (y + height > bottom) beginPage()
    }

    fun gap(amount: Float) {
        y += amount
    }

    fun title(text: String) = draw(text, size = 22f, bold = true, color = Color.BLACK, spacing = 6f)
    fun heading(text: String) {
        gap(6f)
        draw(text, size = 13f, bold = true, color = Color.BLACK, spacing = 4f)
    }
    fun body(text: String) = draw(text, size = 10f, bold = false, color = Color.DKGRAY, spacing = 3f)
    fun caption(text: String) = draw(text, size = 8.5f, bold = false, color = Color.GRAY, spacing = 3f)
    fun mono(text: String) = draw(text, size = 8.5f, bold = false, color = Color.BLACK, spacing = 4f, mono = true)

    fun field(label: String, value: String) {
        val labelPaint = textPaint(10f, bold = true, color = Color.DKGRAY)
        val valuePaint = textPaint(10f, bold = false, color = Color.BLACK)
        val valueLayout = staticLayout(value, valuePaint, contentWidth - 140f)
        val height = maxOf(valueLayout.height.toFloat(), 13f)
        ensure(height + 3f)
        val canvas = page!!.canvas
        canvas.save()
        canvas.translate(left, y)
        canvas.drawText(label, 0f, labelPaint.textSize, labelPaint)
        canvas.restore()
        canvas.save()
        canvas.translate(left + 140f, y)
        valueLayout.draw(canvas)
        canvas.restore()
        y += height + 3f
    }

    fun segmentTable(chunks: List<SessionManifest.Chunk>) {
        val ordered = chunks.sortedWith(compareBy({ it.index }, { it.camera }))
        for (chunk in ordered) {
            val label = if (chunk.kind == "lowRes") {
                "${chunk.fileName}  — low-resolution stand-in"
            } else {
                chunk.fileName
            }
            val detail = "${time(chunk.captureStartUTC)} → ${time(chunk.captureEndUTC)}${coordinateSuffix(chunk)}"
            entry(label, detail, chunk.sha256)
        }
    }

    fun mergedTable(merged: List<SessionManifest.MergedVideo>) {
        for (video in merged) {
            entry(video.fileName, "camera: ${video.camera}", video.sha256)
        }
    }

    private fun entry(title: String, detail: String, hash: String?) {
        ensure(34f)
        val canvas = page!!.canvas
        canvas.save()
        canvas.translate(left, y)
        canvas.drawText(title, 0f, 9f, textPaint(9.5f, bold = true, color = Color.BLACK))
        canvas.restore()
        y += 12f
        canvas.save()
        canvas.translate(left, y)
        canvas.drawText(detail, 0f, 8f, textPaint(8.5f, bold = false, color = Color.DKGRAY))
        canvas.restore()
        y += 11f
        val hashText = hash?.let { "SHA-256  $it" } ?: "SHA-256  not recorded"
        canvas.save()
        canvas.translate(left, y)
        canvas.drawText(hashText, 0f, 7f, textPaint(7.5f, bold = false, color = Color.DKGRAY, mono = true))
        canvas.restore()
        y += 15f
    }

    private fun coordinateSuffix(chunk: SessionManifest.Chunk): String {
        val lat = chunk.latitude ?: return ""
        val lon = chunk.longitude ?: return ""
        return String.format(Locale.US, "   %.5f, %.5f", lat, lon)
    }

    private fun time(epochMillis: Long): String {
        val formatter = SimpleDateFormat("HH:mm:ss", Locale.US)
        formatter.timeZone = TimeZone.getTimeZone("UTC")
        return formatter.format(Date(epochMillis))
    }

    private fun draw(text: String, size: Float, bold: Boolean, color: Int, spacing: Float, mono: Boolean = false) {
        val paint = textPaint(size, bold, color, mono)
        val layout = staticLayout(text, paint, contentWidth)
        ensure(layout.height + spacing)
        val canvas = page!!.canvas
        canvas.save()
        canvas.translate(left, y)
        layout.draw(canvas)
        canvas.restore()
        y += layout.height + spacing
    }

    private fun textPaint(size: Float, bold: Boolean, color: Int, mono: Boolean = false): TextPaint =
        TextPaint(Paint.ANTI_ALIAS_FLAG).apply {
            textSize = size
            this.color = color
            typeface = when {
                mono -> Typeface.MONOSPACE
                bold -> Typeface.DEFAULT_BOLD
                else -> Typeface.DEFAULT
            }
        }

    private fun staticLayout(text: String, paint: TextPaint, width: Float): StaticLayout =
        StaticLayout.Builder.obtain(text, 0, text.length, paint, width.toInt().coerceAtLeast(1))
            .setAlignment(Alignment.ALIGN_NORMAL)
            .setLineSpacing(0f, 1f)
            .setIncludePad(false)
            .build()
}
