import Foundation
import UIKit

/// Renders an archived session into a PDF an attorney or an editor can
/// actually work from.
///
/// The raw artefacts are already complete — a manifest of hashes and an RFC
/// 3161 proof — but they are a JSON file and a binary blob, which is to say
/// unreadable to the people who decide what a recording is worth. This turns
/// the same facts into a document: what was filmed, when and where, which
/// files exist, what each one hashes to, and precisely how a third party can
/// check all of it without trusting this app or its author.
///
/// Nothing here is generated or inferred. Every figure is copied from the
/// manifest that was hashed and counter-signed; the report adds presentation,
/// never content.
enum EvidenceReport {

    private static let pageWidth: CGFloat = 595   // A4 at 72 dpi
    private static let pageHeight: CGFloat = 842
    private static let margin: CGFloat = 48

    /// Writes the report to a temporary file and returns its URL.
    static func pdf(for manifest: SessionManifest, hasTimestamp: Bool) throws -> URL {
        let format = UIGraphicsPDFRendererFormat()
        format.documentInfo = [
            kCGPDFContextTitle as String: "Witness recording \(manifest.sessionID.uuidString)",
            kCGPDFContextCreator as String: "Witness",
        ]
        let bounds = CGRect(x: 0, y: 0, width: pageWidth, height: pageHeight)
        let renderer = UIGraphicsPDFRenderer(bounds: bounds, format: format)

        let url = FileManager.default.temporaryDirectory
            .appendingPathComponent("Witness-\(shortID(manifest.sessionID)).pdf")
        try? FileManager.default.removeItem(at: url)

        try renderer.writePDF(to: url) { context in
            var layout = Layout(context: context, bounds: bounds)
            layout.beginPage()

            layout.title("Recording record")
            layout.caption("Generated by Witness on \(Self.absolute(Date()))")
            layout.gap(10)

            layout.heading("Session")
            layout.field("Identifier", manifest.sessionID.uuidString)
            layout.field("Recording began", absolute(manifest.recordingStartedUTC))
            layout.field("Recording ended", absolute(manifest.recordingEndedUTC))
            layout.field("Duration", duration(from: manifest.recordingStartedUTC,
                                              to: manifest.recordingEndedUTC))
            layout.field("Device time zone", manifest.deviceTimeZone)
            layout.field("Segments recorded", "\(manifest.chunkCount)")
            layout.gap(6)

            layout.heading("Capture device")
            layout.field("Device", manifest.deviceModel)
            layout.field("Operating system", "iOS \(manifest.systemVersion)")
            layout.field("Application", "Witness \(manifest.appVersion)")
            layout.gap(6)

            if let coordinate = firstCoordinate(in: manifest) {
                layout.heading("Location")
                layout.field("First fix", String(format: "%.5f, %.5f",
                                                 coordinate.latitude, coordinate.longitude))
                layout.body("Each segment below carries its own coordinates as recorded at the time it was captured. Positions come from the device's location services and are only as precise as those services allowed.")
                layout.gap(6)
            }

            layout.heading("Authenticity")
            if hasTimestamp {
                layout.body("The accompanying manifest.json was counter-signed by an independent RFC 3161 time-stamp authority, which certifies with its own key and clock that the file existed in exactly this form before the time recorded in timestamp.tsr. Because every segment's SHA-256 appears in that manifest, the certification extends to the footage itself.")
                if let authority = manifest.timestampAuthority {
                    layout.field("Authority", authority)
                }
                layout.gap(4)
                layout.body("To verify independently, with no involvement from Witness or its author:")
                layout.mono("openssl ts -verify -data manifest.json \\\n  -in timestamp.tsr -CAfile <authority CA certificate>")
                layout.body("Any modification to the manifest, or to any file whose hash it lists, causes this check to fail.")
                layout.body("Or drop the videos, manifest.json and timestamp.tsr into witnesscamera.com/verify, which runs the same checks inside the browser without uploading anything.")
            } else {
                layout.body("No time-stamp proof accompanies this session: the authority could not be reached when the recording ended. The hashes below are still a complete record of the files as captured, but they are attested by this device alone rather than counter-signed by an independent party.")
            }
            layout.gap(6)

            if let marks = manifest.markers, !marks.isEmpty {
                layout.heading("Moments marked")
                layout.body("Marked by the person recording, during the recording, with a tap or a volume-button press. They are part of the manifest the time-stamp proof covers.")
                for (i, mark) in marks.enumerated() {
                    let offset = Int(mark.timeIntervalSince(manifest.recordingStartedUTC))
                    layout.field("Mark \(i + 1)", "\(absolute(mark))  (\(offset / 60):\(String(format: "%02d", offset % 60)) into the recording)")
                }
                layout.gap(6)
            }

            layout.heading("Segments and hashes")
            layout.body("Each entry is one file as uploaded. A SHA-256 hash identifies a file's contents exactly: recomputing it over a copy and comparing establishes whether that copy is unaltered.")
            layout.gap(4)
            layout.segmentTable(manifest.chunks)

            if let merged = manifest.mergedVideos, !merged.isEmpty {
                layout.gap(6)
                layout.heading("Consolidated videos")
                layout.body("Once every segment was safely uploaded, the segments of each camera were joined into a single file. These are the same footage, not a re-recording.")
                layout.gap(4)
                layout.mergedTable(merged)
            }

            layout.gap(10)
            layout.caption("This document reproduces the contents of manifest.json. Where the two differ, the manifest — being the file the time-stamp proof covers — governs.")
        }
        return url
    }

    // MARK: - Helpers

    private static func shortID(_ id: UUID) -> String {
        String(id.uuidString.prefix(8))
    }

    private static func absolute(_ date: Date) -> String {
        let formatter = DateFormatter()
        formatter.dateFormat = "yyyy-MM-dd HH:mm:ss 'UTC'"
        formatter.timeZone = TimeZone(identifier: "UTC")
        return formatter.string(from: date)
    }

    private static func duration(from start: Date, to end: Date) -> String {
        let seconds = max(0, Int(end.timeIntervalSince(start)))
        let minutes = seconds / 60
        let remainder = seconds % 60
        return minutes > 0 ? "\(minutes) min \(remainder) s" : "\(remainder) s"
    }

    private static func firstCoordinate(in manifest: SessionManifest) -> (latitude: Double, longitude: Double)? {
        for chunk in manifest.chunks.sorted(by: { $0.index < $1.index }) {
            if let latitude = chunk.latitude, let longitude = chunk.longitude {
                return (latitude, longitude)
            }
        }
        return nil
    }
}

// MARK: - Layout

/// Minimal flowing-text layout over a PDF context: tracks a cursor, breaks
/// pages when the next block wouldn't fit, and draws nothing that would
/// silently overflow the page.
private struct Layout {
    let context: UIGraphicsPDFRendererContext
    let bounds: CGRect
    var y: CGFloat = 0

    private var contentWidth: CGFloat { bounds.width - 96 }
    private let left: CGFloat = 48

    init(context: UIGraphicsPDFRendererContext, bounds: CGRect) {
        self.context = context
        self.bounds = bounds
    }

    mutating func beginPage() {
        context.beginPage()
        y = 48
    }

    mutating func ensure(_ height: CGFloat) {
        if y + height > bounds.height - 48 { beginPage() }
    }

    mutating func gap(_ amount: CGFloat) { y += amount }

    mutating func title(_ text: String) {
        draw(text, font: .systemFont(ofSize: 22, weight: .bold), spacing: 6)
    }

    mutating func heading(_ text: String) {
        gap(6)
        draw(text, font: .systemFont(ofSize: 13, weight: .semibold),
             color: .black, spacing: 4)
    }

    mutating func body(_ text: String) {
        draw(text, font: .systemFont(ofSize: 10), color: .darkGray, spacing: 3)
    }

    mutating func caption(_ text: String) {
        draw(text, font: .systemFont(ofSize: 8.5), color: .gray, spacing: 3)
    }

    mutating func mono(_ text: String) {
        draw(text, font: .monospacedSystemFont(ofSize: 8.5, weight: .regular),
             color: .black, spacing: 4)
    }

    mutating func field(_ label: String, _ value: String) {
        let font = UIFont.systemFont(ofSize: 10)
        let labelFont = UIFont.systemFont(ofSize: 10, weight: .medium)
        let height = max(value.height(width: contentWidth - 140, font: font), 13)
        ensure(height + 3)
        label.draw(in: CGRect(x: left, y: y, width: 136, height: height),
                   withAttributes: [.font: labelFont, .foregroundColor: UIColor.darkGray])
        value.draw(in: CGRect(x: left + 140, y: y, width: contentWidth - 140, height: height),
                   withAttributes: [.font: font, .foregroundColor: UIColor.black])
        y += height + 3
    }

    mutating func segmentTable(_ chunks: [SessionManifest.Chunk]) {
        let ordered = chunks.sorted { ($0.index, $0.camera) < ($1.index, $1.camera) }
        for chunk in ordered {
            let label = chunk.kind == ChunkRecord.Kind.lowRes.rawValue
                ? "\(chunk.fileName)  — low-resolution stand-in"
                : chunk.fileName
            entry(title: label,
                  detail: "\(Layout.time(chunk.captureStartUTC)) → \(Layout.time(chunk.captureEndUTC))"
                        + coordinateSuffix(chunk),
                  hash: chunk.sha256)
        }
    }

    mutating func mergedTable(_ merged: [SessionManifest.MergedVideo]) {
        for video in merged {
            entry(title: video.fileName, detail: "camera: \(video.camera)", hash: video.sha256)
        }
    }

    private mutating func entry(title: String, detail: String, hash: String?) {
        ensure(34)
        title.draw(in: CGRect(x: left, y: y, width: contentWidth, height: 12),
                   withAttributes: [.font: UIFont.systemFont(ofSize: 9.5, weight: .medium),
                                    .foregroundColor: UIColor.black])
        y += 12
        detail.draw(in: CGRect(x: left, y: y, width: contentWidth, height: 11),
                    withAttributes: [.font: UIFont.systemFont(ofSize: 8.5),
                                     .foregroundColor: UIColor.darkGray])
        y += 11
        let hashText = hash.map { "SHA-256  \($0)" } ?? "SHA-256  not recorded"
        hashText.draw(in: CGRect(x: left, y: y, width: contentWidth, height: 11),
                      withAttributes: [.font: UIFont.monospacedSystemFont(ofSize: 7.5, weight: .regular),
                                       .foregroundColor: UIColor.darkGray])
        y += 15
    }

    private func coordinateSuffix(_ chunk: SessionManifest.Chunk) -> String {
        guard let latitude = chunk.latitude, let longitude = chunk.longitude else { return "" }
        return String(format: "   %.5f, %.5f", latitude, longitude)
    }

    private static func time(_ date: Date) -> String {
        let formatter = DateFormatter()
        formatter.dateFormat = "HH:mm:ss"
        formatter.timeZone = TimeZone(identifier: "UTC")
        return formatter.string(from: date)
    }

    private mutating func draw(_ text: String, font: UIFont,
                               color: UIColor = .black, spacing: CGFloat) {
        let height = text.height(width: contentWidth, font: font)
        ensure(height + spacing)
        text.draw(in: CGRect(x: left, y: y, width: contentWidth, height: height),
                  withAttributes: [.font: font, .foregroundColor: color])
        y += height + spacing
    }
}

private extension String {
    func height(width: CGFloat, font: UIFont) -> CGFloat {
        let rect = (self as NSString).boundingRect(
            with: CGSize(width: width, height: .greatestFiniteMagnitude),
            options: [.usesLineFragmentOrigin, .usesFontLeading],
            attributes: [.font: font],
            context: nil)
        return ceil(rect.height)
    }
}
